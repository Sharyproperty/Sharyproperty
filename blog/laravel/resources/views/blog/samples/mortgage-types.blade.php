<p><strong>التمويل العقاري في مصر</strong> وسيلة لشراء وحدة سكنية وسداد ثمنها على سنوات طويلة عن طريق بنك أو شركة تمويل مرخصة، مقابل رهن الوحدة لصالح جهة التمويل حتى اكتمال السداد. في هذا المقال نشرح أنواع التمويل العقاري المتاحة، والفرق بينها وبين تقسيط المطور، والشروط والأوراق المطلوبة، وكيف تختار النظام الأنسب لدخلك.</p>

<h2 id="what">ما هو التمويل العقاري؟</h2>

<p>التمويل العقاري اتفاق ثلاثي بين المشتري والبائع وجهة التمويل: تسدد الجهة ثمن الوحدة أو جزءًا منه للبائع، ويسدد المشتري المبلغ على أقساط شهرية مضافًا إليها عائد متفق عليه. وينظم هذا النشاط قانون التمويل العقاري رقم 148 لسنة 2001، وتخضع البنوك لرقابة البنك المركزي المصري، وشركات التمويل العقاري لرقابة الهيئة العامة للرقابة المالية.</p>

<h2 id="types">أنواع التمويل العقاري في مصر</h2>

<ul>
    <li><strong>تمويل البنوك</strong> <span>قرض عقاري بعائد يحدده كل بنك وفق سعر العائد السائد، ومدد سداد طويلة تصل في بعض البرامج إلى 20 سنة أو أكثر.</span></li>
    <li><strong>شركات التمويل العقاري</strong> <span>شركات مرخصة من الهيئة العامة للرقابة المالية، تتميز غالبًا بمرونة أكبر في إثبات الدخل وسرعة الإجراءات، مقابل تكلفة تمويل قد تكون أعلى.</span></li>
    <li><strong>مبادرات التمويل المدعومة</strong> <span>برامج يطرحها البنك المركزي وصندوق الإسكان الاجتماعي ودعم التمويل العقاري لمحدودي ومتوسطي الدخل بعائد مخفّض، وفق شروط محددة للدخل وسعر الوحدة ومساحتها.</span></li>
    <li><strong>التمويل المتوافق مع الشريعة</strong> <span>صيغ مثل المرابحة والإجارة المنتهية بالتمليك تقدمها البنوك الإسلامية وبعض شركات التمويل.</span></li>
</ul>

