<h2 id="requirements">شروط التمويل العقاري والأوراق المطلوبة</h2>

<p>تختلف التفاصيل من جهة لأخرى، لكن أغلب الجهات تطلب:</p>

<ul>
    <li>بطاقة رقم قومي سارية وإيصال مرافق حديث لمحل الإقامة.</li>
    <li>إثبات دخل: شهادة مرتب أو كشف حساب بنكي، أو سجل تجاري وبطاقة ضريبية لأصحاب الأعمال.</li>
    <li>مستندات الوحدة: عقد الملكية أو التخصيص وما يثبت إمكانية قيد الرهن عليها.</li>
    <li>سجل ائتماني منتظم لدى شركة الاستعلام الائتماني.</li>
</ul>

<h2 id="installment">كيف تحسب القسط المناسب لدخلك؟</h2>

<p>تضع جهات التمويل حدًا أقصى لنسبة إجمالي الأقساط إلى الدخل الشهري وفق قواعد البنك المركزي وشروط كل برنامج. وقبل أن تتقدم بطلبك:</p>

<ol>
    <li>احسب صافي دخلك الشهري الثابت، واطرح منه التزاماتك وأقساطك الحالية.</li>
    <li>اطلب جدول سداد كاملًا يوضح قيمة القسط وإجمالي ما ستدفعه حتى نهاية المدة.</li>
    <li>قارن بين أكثر من عرض على أساس إجمالي التكلفة، لا قيمة القسط فقط.</li>
    <li>اترك هامشًا للطوارئ، ولا تلتزم بقسط عند الحد الأقصى المسموح.</li>
</ol>

<h2 id="mistakes">أخطاء شائعة عند طلب التمويل العقاري</h2>

<ul>
    <li>النظر إلى قيمة القسط وإهمال إجمالي التكلفة على مدار سنوات السداد.</li>
    <li>إغفال المصروفات الإدارية ورسوم التقييم والتأمين.</li>
    <li>اختيار وحدة لا يمكن تسجيلها أو رهنها، فيُرفض الطلب بعد دفع جدية الحجز.</li>
</ul>

