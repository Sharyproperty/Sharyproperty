<h2 id="payment">Payment and installment plans</h2>
<p>Most developers in the New Capital offer flexible payment plans, with a down payment that usually starts from 5% to 10% of the unit price and the balance paid in installments over up to 8 or 10 years. Terms differ from one project to another, so compare the total price, the down payment and the delivery date, not just the installment amount.</p>

<h2 id="pros-cons">Pros and cons of living in the New Capital</h2>
<ul>
    <li><strong>Modern planning</strong> <span>Wide streets, green spaces and smart infrastructure designed from scratch.</span></li>
    <li><strong>Full services</strong> <span>Education, healthcare, business and leisure inside the city itself.</span></li>
    <li><strong>Variety of units</strong> <span>Apartments, duplexes, villas, and office and retail units in different sizes and payment plans.</span></li>
    <li><strong>Distance from central Cairo</strong> <span>Still relatively far for anyone whose work is in downtown or West Cairo.</span></li>
    <li><strong>Uneven occupancy</strong> <span>Some areas are still under construction, so check the build progress and actual occupancy around the unit.</span></li>
</ul>

