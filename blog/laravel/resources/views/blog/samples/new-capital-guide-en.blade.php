<h2 id="tips">Tips before buying a unit in the New Capital</h2>
<ol>
    <li>Review the developer’s track record and how well it met delivery dates in earlier projects.</li>
    <li>Check the ministerial decree and project licences, and visit the site to see the actual build progress.</li>
    <li>Read the contract carefully: delivery date, delay penalties and the maintenance deposit.</li>
    <li>Compare the average price per meter in the same district before negotiating the price.</li>
    <li>Be clear about your goal: living needs closeness to services, while investment needs a location with resale or rental demand.</li>
</ol>
