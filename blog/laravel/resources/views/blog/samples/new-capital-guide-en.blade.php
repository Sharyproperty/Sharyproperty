<h2 id="districts">Residential districts in the New Capital</h2>
<p>Phase one includes eight residential districts, labelled R1 to R8, alongside the Government District, the Central Business District and the Diplomatic District. These are the districts buyers ask about most:</p>
<ul>
    <li><strong>Third Residential District (R3)</strong> <span>Home to the state-built “Capital Residence” project, and one of the first districts to be lived in.</span></li>
    <li><strong>Fifth Residential District (R5)</strong> <span>Known as “New Garden City”, with wide green spaces and mid-rise buildings.</span></li>
    <li><strong>Seventh Residential District (R7)</strong> <span>The most in-demand district, with many private developers’ compounds near the Green River and the Diplomatic District.</span></li>
    <li><strong>Eighth Residential District (R8)</strong> <span>A newer district with projects by major developers, close to the embassies area and the main roads.</span></li>
</ul>

