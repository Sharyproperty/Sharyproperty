<h2 id="districts">الأحياء السكنية في العاصمة الإدارية</h2>
<p>تضم المرحلة الأولى من العاصمة ثمانية أحياء سكنية يُرمز لها بالحرف R (من R1 إلى R8)، إلى جانب الحي الحكومي وحي المال والأعمال والحي الدبلوماسي. وهذه أشهر الأحياء التي يكثر السؤال عنها:</p>
<ul>
    <li><strong>الحي السكني الثالث R3</strong> <span>يضم مشروع «كابيتال ريزيدنس» الذي نفذته الدولة، وهو من أوائل الأحياء التي سُكنت فعليًا.</span></li>
    <li><strong>الحي السكني الخامس R5</strong> <span>يُعرف باسم «جاردن سيتي الجديدة»، ويتميز بمساحات خضراء واسعة وعمارات متوسطة الارتفاع.</span></li>
    <li><strong>الحي السكني السابع R7</strong> <span>أكثر الأحياء طلبًا، ويضم عددًا كبيرًا من كمبوندات المطورين العقاريين بالقرب من النهر الأخضر والمنطقة الدبلوماسية.</span></li>
    <li><strong>الحي السكني الثامن R8</strong> <span>حي حديث يضم مشروعات لكبار المطورين، ويتميز بقربه من حي السفارات ومحاور الحركة الرئيسية.</span></li>
</ul>

