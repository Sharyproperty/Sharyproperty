<p><strong>Mortgage finance in Egypt</strong> lets you buy a home and pay for it over many years through a bank or a licensed finance company, with the unit mortgaged to the lender until the loan is repaid. This article explains the types available, how they differ from a developer’s installment plan, the conditions and documents required, and how to choose what fits your income.</p>

<h2 id="what">What is mortgage finance?</h2>

<p>It is a three-party agreement between the buyer, the seller and the lender: the lender pays all or part of the price to the seller, and the buyer repays it in monthly installments plus an agreed return. The activity is governed by Mortgage Finance Law No. 148 of 2001. Banks are supervised by the Central Bank of Egypt, and mortgage finance companies by the Financial Regulatory Authority.</p>

<h2 id="types">Types of mortgage finance in Egypt</h2>

<ul>
    <li><strong>Bank mortgages</strong> <span>A home loan at a rate each bank sets from the prevailing rate, with long terms that reach 20 years or more in some programs.</span></li>
    <li><strong>Mortgage finance companies</strong> <span>Licensed by the Financial Regulatory Authority, usually more flexible on proof of income and faster to process, at a cost that may be higher.</span></li>
    <li><strong>Subsidised initiatives</strong> <span>Programs from the Central Bank and the Social Housing and Mortgage Finance Fund for low- and middle-income buyers at a reduced rate, subject to limits on income, unit price and area.</span></li>
    <li><strong>Sharia-compliant finance</strong> <span>Structures such as Murabaha and Ijara offered by Islamic banks and some finance companies.</span></li>
</ul>

<h2 id="developer">Mortgage finance vs the developer’s installment plan</h2>

<table>
    <thead>
        <tr><th>Point</th><th>Mortgage finance</th><th>Developer installments</th></tr>
    </thead>
    <tbody>
        <tr><th>Unit status</th><td>Usually a finished unit that can be mortgaged</td><td>Usually under construction</td></tr>
        <tr><th>Term</th><td>Long, can exceed 15 years</td><td>Usually 5 to 10 years</td></tr>
        <tr><th>Cost</th><td>A stated return on top of the principal</td><td>Built into the unit price</td></tr>
        <tr><th>Requirements</th><td>Proof of income, credit check and unit appraisal</td><td>Reservation payment and a contract with the developer</td></tr>
    </tbody>
</table>

<h2 id="requirements">Conditions and required documents</h2>

<p>Details differ between lenders, but most ask for:</p>

<ul>
    <li>A valid national ID and a recent utility bill for your address.</li>
    <li>Proof of income: a salary certificate or bank statement, or a commercial register and tax card for business owners.</li>
    <li>The unit’s documents: the ownership or allocation contract and proof that a mortgage can be registered on it.</li>
    <li>A clean record with the credit bureau.</li>
</ul>

<h2 id="installment">How to work out an installment that fits your income</h2>

<p>Lenders cap total installments as a share of monthly income, under Central Bank rules and each program’s terms. Before you apply:</p>

<ol>
    <li>Work out your fixed net monthly income and subtract your current commitments and installments.</li>
    <li>Ask for a full repayment schedule showing the installment and the total you will pay by the end of the term.</li>
    <li>Compare several offers by total cost, not by the installment alone.</li>
    <li>Leave room for emergencies and avoid committing to the maximum allowed.</li>
</ol>

<h2 id="mistakes">Common mistakes when applying</h2>

<ul>
    <li>Looking at the installment and ignoring the total cost over the years of repayment.</li>
    <li>Overlooking administrative fees, appraisal fees and insurance.</li>
    <li>Choosing a unit that cannot be registered or mortgaged, so the application is rejected after the reservation is paid.</li>
</ul>

